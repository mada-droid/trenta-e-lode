const { contextBridge, ipcRenderer, webUtils } = require('electron');
const inv = (ch, ...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld('api', {
  load: () => inv('state:load'),
  save: s => inv('state:save', s),
  backup: s => inv('state:backup', s),
  info: () => inv('app:info'),
  hubInit: h => inv('hub:init', h),
  pickHub: () => inv('hub:pick'),
  openPdf: (root, rel, page) => inv('pdf:open', root, rel, page),
  notify: (t, b) => inv('notify', t, b),
  compact: on => inv('compact', on),
  fullscreen: on => inv('fullscreen', on),
  win: c => ipcRenderer.send('win', c),
  openUrl: url => inv('url:open', url),
  offline: () => inv('offline:load'),
  prefs: p => ipcRenderer.send('prefs', p),
  status: s => ipcRenderer.send('status', s),
  geoSearch: q => inv('geo:search', q),
  prayerSet: loc => inv('prayer:set', loc),
  contentDownload: what => inv('content:download', what),
  bgStatus: files => inv('bg:status', files),
  bgDownload: file => inv('bg:download', file),
  subjects: folders => inv('subjects:read', folders),
  subjectFolder: name => inv('subject:folder', name),
  subjectRename: (from, to) => inv('subject:rename', from, to),
  subjectRemove: folder => inv('subject:remove', folder),
  subjectMerge: (folder, data) => inv('subject:merge', folder, data),
  pickFiles: () => inv('files:pick'),
  importFiles: (folder, topic, paths) => inv('files:import', folder, topic, paths),
  openFile: rel => inv('files:open', rel),
  revealFile: rel => inv('files:reveal', rel),
  openFolder: which => inv('folder:open', which),
  hasClaude: () => inv('ai:hasClaude'),
  aiRequest: r => inv('ai:request', r),
  ytCheck: ids => inv('yt:check', ids),
  lofiResolve: (src, opts) => inv('lofi:resolve', src, opts),
  testPopup: kind => inv('popup:test', kind),
  popupHistory: () => inv('popup:history'),
  pathOf: file => webUtils.getPathForFile(file),
  on: (ch, cb) => ipcRenderer.on(ch, (_e, d) => cb(d)),
});
